# Bundles the app's business-logic files (tools/core-src/*.js, CommonJS) into one browser script, js/core.js.
# Run from the repository root:   python3 tools/build-core.py
import os
here = os.path.dirname(os.path.abspath(__file__))
src = os.path.join(here, 'core-src')
out = os.path.join(here, '..', 'js', 'core.js')
mods = [('./dates', 'dates.web.js'), ('./logic', 'logic.js'), ('./seed', 'seed.web.js'), ('./db', 'db.js'), ('./reports', 'reports.web.js')]
parts = ["// Generated by tools/build-core.py from tools/core-src/*.js (originally the PADMA HOSTEL FINANCE desktop app). Do not edit by hand.",
         "(function (global) {", "'use strict';", "const __defs = {}, __cache = {};", "const __stub = {};",
         "function require(name) {",
         "  if (name === 'fs' || name === 'path') return __stub;",
         "  if (__cache[name]) return __cache[name].exports;",
         "  const module = { exports: {} }; __cache[name] = module;",
         "  __defs[name](module, module.exports); return module.exports;", "}"]
for name, f in mods:
    code = open(os.path.join(src, f), encoding='utf-8').read()
    parts.append(f"__defs['{name}'] = function (module, exports) {{\n{code}\n}};")
parts.append("global.PadmaCore = { dates: require('./dates'), logic: require('./logic'), db: require('./db'), reports: require('./reports') };")
parts.append("})(window);")
open(out, 'w', encoding='utf-8').write('\n'.join(parts) + '\n')
print('wrote', os.path.normpath(out))
